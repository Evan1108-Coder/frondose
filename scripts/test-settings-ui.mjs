// Isolated UI regression suite. Set RUMBO_PLAYWRIGHT_MODULE to an installed Playwright module when it is not a project dependency.
import assert from 'node:assert/strict';
import { mkdtemp, rm, readFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createServer } from 'vite';
import react from '@vitejs/plugin-react';
const { chromium } = await import(process.env.RUMBO_PLAYWRIGHT_MODULE || 'playwright');
import { createLocalApi } from '../server/local-api.mjs';
import { SETTINGS_GROUPS, PAGE_RESOURCE, RESOURCE_TYPES } from '../src/lib/settings-catalog.js';
const dir = await mkdtemp(join(tmpdir(), 'rumbo-settings-browser-'));
const forbidden = () => { throw new Error('Provider calls prohibited in browser QA'); };
const api = createLocalApi({ dataDir: dir, integrationOptions: { env: {}, execute: forbidden, spawnProcess: forbidden, fetchImpl: forbidden } });
const server = await createServer({ root: new URL('../', import.meta.url).pathname, cacheDir: join(dir, 'vite-cache'), configFile: false, server: { host: '127.0.0.1', port: 4195, strictPort: true }, plugins: [react(), { name: 'isolated-api', configureServer(server) { server.middlewares.use(api.middleware); } }] });
await server.listen();
const base = 'http://127.0.0.1:4195';
const post = async (path, body) => { const r = await fetch(base + '/api' + path, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) }); const d = await r.json(); assert.ok(r.ok, JSON.stringify(d)); return d; };
const workspace = (await post('/workspaces', { name: 'Atlas Studio', description: 'A focused place for people and agents.' })).workspace;
const team = (await post('/teams', { workspace_id: workspace.id, name: 'Product studio' })).team;
const project = (await post('/projects', { workspace_id: workspace.id, team_id: team.id, name: 'SourceLens', goal: 'Make research easier.' })).project;
await post('/agents', { workspace_id: workspace.id, name: 'Reviewer', provider: 'codex' });
await post('/documents', { workspace_id: workspace.id, project_id: project.id, title: 'Product brief', content: '# Intent\nUseful, trustworthy research.' });
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
page.on('console', msg => { if (msg.type() === 'error') errors.push(msg.text()); });
const go = async section => { await page.goto(`${base}/#/settings/${section}`); await page.locator('.settings-body').waitFor(); await page.waitForTimeout(100); };
const select = async (label, option) => { await page.getByRole('combobox', { name: label, exact: true }).click(); await page.getByRole('option', { name: option, exact: true }).click(); };
try {
  await go('preferences');
  assert.match(await page.title(), /Rumbo/);
  for (const [, sections] of SETTINGS_GROUPS) for (const [id] of sections) {
    await go(id);
    assert.ok((await page.locator('.settings-body').innerText()).trim().length > 10, id);
    assert.equal(await page.locator('vite-error-overlay').count(), 0, id);
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
    assert.equal(overflow, false, `${id} overflows desktop`);
  }
  console.log('Round 1: all settings pages render without runtime errors');
  await go('route-labels');
  await page.getByRole('button', { name: 'New label', exact: true }).first().click();
  await page.getByRole('textbox', { name: 'Name', exact: true }).fill('Research');
  await page.getByRole('textbox', { name: 'Group', exact: true }).fill('Work type');
  await page.getByRole('textbox', { name: 'Description', exact: true }).fill('Exploration and discovery work.');
  await page.getByRole('button', { name: 'Save label', exact: true }).click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  assert.match(await page.locator('.resource-list').innerText(), /Research/);
  await page.screenshot({ path: '/tmp/rumbo-settings-labels-desktop.png' });
  await page.getByRole('button', { name: 'Edit Research', exact: true }).click();
  await page.getByRole('textbox', { name: 'Name', exact: true }).fill('Research draft');
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  await page.getByRole('button', { name: 'Discard changes', exact: true }).click();
  assert.match(await page.locator('.resource-list').innerText(), /Research/);
  assert.doesNotMatch(await page.locator('.resource-list').innerText(), /Research draft/);
  await go('route-workflow');
  await page.getByRole('button', { name: 'New status', exact: true }).first().click();
  await page.getByRole('textbox', { name: 'Name', exact: true }).fill('Ready for feedback');
  await select('Lifecycle stage', 'Review');
  await page.getByRole('button', { name: 'Save status', exact: true }).click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  await page.screenshot({ path: '/tmp/rumbo-settings-workflow-desktop.png' });
  await go('route-templates');
  await page.getByRole('button', { name: 'New template', exact: true }).first().click();
  await page.getByRole('textbox', { name: 'Name', exact: true }).fill('Investigation');
  await page.getByRole('textbox', { name: 'Route brief / checklist', exact: true }).fill('Document the question and sources.');
  await select('Starting stage', 'Ready');
  await page.getByRole('button', { name: 'Save template', exact: true }).click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: 'Use template', exact: true }).click();
  await page.getByRole('textbox', { name: 'Name for the new item' }).fill('Investigate citations');
  await page.getByRole('button', { name: 'Create from template', exact: true }).click();
  await page.waitForURL(/#\/tasks\//);
  await select('Status', 'Ready for feedback · Review');
  await page.getByRole('checkbox', { name: 'Research', exact: true }).check();
  await page.waitForTimeout(200);
  await page.reload();
  assert.match(await page.getByRole('combobox', { name: 'Status', exact: true }).innerText(), /Ready for feedback/);
  assert.equal(await page.getByRole('checkbox', { name: 'Research', exact: true }).isChecked(), true);
  await go('preferences');
  await select('Send messages with', 'Cmd / Ctrl + Enter');
  await select('First day of week', 'Sunday');
  await select('Default home', 'Focus');
  await page.reload();
  assert.match(await page.getByRole('combobox', { name: 'Send messages with', exact: true }).innerText(), /Cmd/);
  await go('requests');
  await page.getByRole('button', { name: 'New request', exact: true }).first().click();
  await page.getByRole('textbox', { name: 'Name', exact: true }).fill('Improve onboarding');
  await page.getByRole('button', { name: 'Save request', exact: true }).click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: 'Create route', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Create route', exact: true }).click();
  await page.waitForURL(/#\/tasks\//);
  await go('audit');
  assert.match(await page.locator('.settings-directory').innerText(), /Research/);
  await go('usage');
  await page.screenshot({ path: '/tmp/rumbo-settings-usage-desktop.png' });
  console.log('Round 1: labels, unsaved changes, custom workflow, templates, preferences, requests, history passed');
  for (const size of [390, 320]) {
    await page.setViewportSize({ width: size, height: 844 });
    for (const section of ['preferences', 'route-labels', 'route-workflow', 'route-templates', 'usage', 'integrations', 'documents', 'teams', 'security', 'storage']) {
      await go(section);
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `${section} overflows ${size}`);
      assert.equal(await page.locator('.settings-body').isVisible(), true);
    }
    await go('route-labels');
    await page.screenshot({ path: `/tmp/rumbo-settings-labels-${size}.png` });
  }
  await page.setViewportSize({ width: 1440, height: 1000 });
  await go('appearance');
  await page.getByRole('button', { name: 'Light', exact: true }).click();
  await go('route-labels');
  await page.screenshot({ path: '/tmp/rumbo-settings-labels-light.png' });
  assert.equal(await page.locator('html').getAttribute('data-theme'), 'light');
  console.log('Round 2: creating every resource through its authored editor');
  for (const [section, kind] of Object.entries(PAGE_RESOURCE)) {
    await go(section);
    const spec = RESOURCE_TYPES[kind];
    await page.getByRole('button', { name: `New ${spec.singular}`, exact: true }).first().click();
    await page.getByRole('textbox', { name: 'Name', exact: true }).fill(`QA ${kind}`);
    if (kind === 'emoji') await page.getByRole('textbox', { name: 'Emoji', exact: true }).fill('🧭');
    await page.getByRole('button', { name: `Save ${spec.singular}`, exact: true }).click();
    await page.getByRole('dialog').waitFor({ state: 'hidden' });
    await page.reload();
    await page.getByRole('button', { name: `Edit QA ${kind}`, exact: true }).waitFor();
    await page.getByRole('button', { name: `Archive QA ${kind}`, exact: true }).click();
    await page.getByRole('dialog').getByRole('button', { name: 'Archive', exact: true }).click();
    await page.getByRole('dialog').waitFor({ state: 'hidden' });
    await select('Show items', 'Archived');
    await page.getByRole('button', { name: 'Restore', exact: true }).click();
    await select('Show items', 'Active');
    await page.getByRole('button', { name: `Edit QA ${kind}`, exact: true }).waitFor();
  }
  await go('route-labels');
  await page.locator('.resource-row').filter({ hasText: 'Research' }).getByRole('button', { name: 'Merge', exact: true }).click();
  await select('Merge into', 'QA route_label');
  await page.getByRole('button', { name: 'Merge labels', exact: true }).click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  const mergedLabel = api.snapshot().workspace_items.find(i => i.name === 'QA route_label');
  assert.ok(api.snapshot().tasks.find(t => t.title === 'Investigate citations').labels.includes(mergedLabel.id));
  await go('automations');
  await page.getByRole('button', { name: 'Edit QA automation', exact: true }).click();
  await select('Move matching routes to', 'Ready');
  await page.getByRole('button', { name: 'Save rule', exact: true }).click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: 'Preview rule', exact: true }).click();
  await page.getByRole('button', { name: 'Apply to these routes', exact: true }).click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  assert.equal(api.snapshot().tasks.find(t => t.title === 'Improve onboarding').status, 'ready');
  await go('storage');
  const downloading = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export JSON', exact: true }).click();
  const downloaded = await downloading;
  const archive = JSON.parse(await readFile(await downloaded.path(), 'utf8'));
  assert.equal(archive.format, 'rumbo.workspace');
  await page.locator('input[type=file]').setInputFiles({ name: 'workspace.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(archive)) });
  await page.getByRole('button', { name: 'Import content', exact: true }).click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  await page.waitForTimeout(200);
  assert.equal(api.snapshot().workspaces.filter(w => w.name === 'Atlas Studio (imported)').length, 1);
  await go('appearance');
  await page.getByRole('button', { name: 'Dark', exact: true }).click();
  await go('route-labels');
  await page.screenshot({ path: '/tmp/rumbo-settings-final-desktop.png' });
  console.log('Round 2: all 19 editors, archive/restore, label merge, rule application and safe import passed');
  assert.deepEqual(errors, []);
  assert.equal(api.snapshot().runs.length, 0);
  console.log('Round 1: responsive, light theme, zero console errors, zero AI sessions passed');
} finally { await browser.close(); await server.close(); api.close(); await rm(dir, { recursive: true, force: true }); }
