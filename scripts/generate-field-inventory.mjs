// Mechanical generated catalog for Node tests and source review. Development
// and production Vite loads always discover current JSX through the plugin.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { discoverSourceFields } from './field-defaults-transform.mjs';
const root = fileURLToPath(new URL('../', import.meta.url));
const fields = discoverSourceFields(root);
writeFileSync(new URL('../src/lib/field-source-inventory.js', import.meta.url), `// Generated by scripts/generate-field-inventory.mjs. Vite serves a current catalog from the same analyzer.\n// Semantic file/component/form/field identities; never DOM IDs, source line numbers or row indexes.\nexport const SOURCE_FIELD_DEFINITIONS = ${JSON.stringify(fields, null, 2)};\n`);
console.log(`Generated ${fields.length} source input definitions.`);
