import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createServer } from 'node:http';
import { DatabaseSync } from 'node:sqlite';
import { createLocalApi } from '../server/local-api.mjs';
import { getInspection, captureRunContext } from '../server/run-context-store.mjs';

test('authenticated coordination routes save idempotent records and prepare a protected draft without inference', async t => {
  const directory = await mkdtemp(join(tmpdir(),'talvori-coordination-api-'));
  let providerCalls = 0;
  const forbidden = () => { providerCalls++; throw Error('No live provider calls in coordination tests.'); };
  const api = createLocalApi({dataDir:directory,seedMode:'clean',integrationOptions:{env:{},execute:forbidden,spawnProcess:forbidden,fetchImpl:forbidden}});
  const db = new DatabaseSync(api.dbPath), server = createServer(api.middleware);
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  t.after(async()=>{api.close();await new Promise(resolve=>server.close(resolve));db.close();await rm(directory,{recursive:true,force:true});});
  const request = async(path,body,method=body===undefined?'GET':'POST')=>{
    const response=await fetch(`http://127.0.0.1:${server.address().port}/api${path}`,{method,headers:body===undefined?{}:{'Content-Type':'application/json'},body:body===undefined?undefined:JSON.stringify(body)});
    return {status:response.status,body:await response.json()};
  };
  const call=async(path,body,method)=>{const response=await request(path,body,method);assert.ok(response.status>=200&&response.status<300,JSON.stringify(response));return response.body;};
  const workspace=(await call('/workspaces',{name:'Coordination fixture'})).workspace;
  const agent=(await call('/agents',{workspace_id:workspace.id,name:'Coordination source',provider:'codex'})).agent;
  const recipient=(await call('/agents',{workspace_id:workspace.id,name:'Coordination recipient',provider:'openai'})).agent;
  const chat=(await call('/chats',{workspace_id:workspace.id,title:'Source',participant_agent_ids:[agent.id]})).chat;
  const target=(await call('/chats',{workspace_id:workspace.id,title:'Recipient',participant_agent_ids:[recipient.id]})).chat;
  const input={workspace_id:workspace.id,chat_id:chat.id,agent_id:agent.id,prompt:'Initial reviewed prompt',work_mode:'conversation',include_chat:false,include_memory:false};
  const preview=(await call('/context/inspect',input)).result;
  const captured=getInspection(db,preview.id,{actorId:'local-owner',workspaceId:workspace.id}).inspection;
  const now=new Date().toISOString();
  db.prepare('INSERT INTO runs(id,workspace_id,chat_id,agent_id,provider,agent_name,status,title,prompt,mode,work_mode,created_at,updated_at) VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?)').run('fixture-run',workspace.id,chat.id,agent.id,'codex',agent.name,'running','Fixture work','Initial reviewed prompt','live','conversation',now,now);
  captureRunContext(db,'fixture-run',captured);
  const message={request_id:'coordination-api-request',kind:'handoff',content:'Please independently check this result.',target_chat_id:target.id,target_agent_id:recipient.id};
  const created=await request('/runs/fixture-run/coordination',message), replay=await request('/runs/fixture-run/coordination',message);
  assert.equal(created.status,201);assert.equal(replay.status,200);assert.equal(created.body.result.id,replay.body.result.id);
  assert.equal((await request('/runs/fixture-run/coordination',{...message,content:'Different'})).status,409);
  const listed=(await call('/runs/fixture-run/coordination')).result;
  assert.equal(listed.items.length,1);assert.equal(listed.capabilities.auto_dispatch,false);
  assert.doesNotMatch(JSON.stringify(listed),/actionNonce|runtimeProtocol|finalPrompt|source_access_json/);
  const prepared=(await call(`/runs/fixture-run/coordination/${created.body.result.id}/prepare`,{})).result;
  assert.equal(prepared.dispatched,false);assert.equal(prepared.agent_id,recipient.id);
  const snapshot=(await call(`/chat-collaboration/${target.id}/snapshots/${prepared.context.id}?workspace_id=${workspace.id}`)).result;
  assert.equal(snapshot.content,prepared.context.content);
  const followUp={workspace_id:workspace.id,chat_id:target.id,agent_id:recipient.id,prompt:prepared.content,work_mode:'conversation',include_chat:false,include_memory:false,attachments:[{name:`talvori-context-${snapshot.id}.md`,type:'text/markdown',content:snapshot.content,rumbo_context_snapshot:snapshot.id}]};
  const followUpPreview=(await call('/context/inspect',followUp)).result;
  assert.match(followUpPreview.finalPrompt,/Please independently check this result/);
  assert.equal(db.prepare('SELECT count(*) n FROM runs').get().n,1);
  assert.equal(db.prepare('SELECT count(*) n FROM chat_turns').get().n,0);
  assert.equal(db.prepare('SELECT count(*) n FROM messages').get().n,0);
  assert.equal(db.prepare("SELECT count(*) n FROM run_events WHERE type='coordination.recorded'").get().n,1);
  assert.equal(providerCalls,0);
  assert.equal((await request('/runs/fixture-run/coordination',{...message,request_id:'spoof',author_type:'agent'})).status,400);
  assert.equal((await request('/runs/no-run/coordination')).status,404);
});
