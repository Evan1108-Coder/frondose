function freezeDeep(value) {
  if (!value || typeof value !== 'object' || Object.isFrozen(value)) return value;
  Object.values(value).forEach(freezeDeep);
  return Object.freeze(value);
}

function normalize(entry, native = false) {
  const launchTemplate = [...entry.command];
  const requiresInstallApproval = ['npx', 'uvx'].includes(launchTemplate[0]);
  return {
    id: entry.id,
    title: entry.title,
    description: entry.description || entry.title + ' on your connected computer',
    protocol: entry.protocol || 'acp',
    method: 'computer',
    sourceKind: entry.sourceKind || (entry.bundledProvider ? 'bundled-plugin' : 'acp-catalog'),
    sourceRevision: PASEO_SOURCE.revision,
    sourceUrl: PASEO_SOURCE.url + '/blob/' + PASEO_SOURCE.revision + '/' + (entry.sourcePath || (native ? 'packages/protocol/src/provider-manifest.ts' : PASEO_SOURCE.catalogPath)),
    sourceLicense: PASEO_SOURCE.license,
    upstreamVersion: entry.version || 'installed-runtime',
    installLink: entry.installLink,
    launchTemplate,
    discoveryCommands: [launchTemplate[0]],
    requiresInstallApproval,
    requiresFullAccess: entry.requiresFullAccess === true,
    enabledByDefault: entry.enabledByDefault !== false,
    authentication: 'provider-owned-login-or-api-key',
    platforms: { darwin: 'unverified', win32: 'unverified', linux: 'unverified', other: 'unsupported' },
    support: {
      catalogued: true,
      adapterStatus: ['claude', 'codex', 'copilot'].includes(entry.id) ? 'existing-local-adapter' : 'not-implemented',
      liveVerified: false,
      platformVerified: [],
      historyImport: 'not-verified',
      sharing: 'requires-explicit-grant-and-provider-permission',
      install: requiresInstallApproval ? 'requires-install-approval' : 'manual-provider-install',
    },
    env: { ...(entry.env || {}) },
    params: { ...(entry.params || {}) },
    securityNotice: entry.securityNotice || 'Runs with the host operating-system account. Catalog presence does not grant tool or workspace access.',
  };
}

